#!/usr/bin/env node
// Alite2 Studio server.
//
// One process does three jobs:
//   1. serves the editor on http://127.0.0.1:<port>  (default 5190) and the Alite2 UI project (/api/project)
//   2. runs a WebSocket bridge: the editor tab connects on /bridge
//   3. speaks MCP over stdio so an AI assistant (Claude Code, Codex, ...) can drive the editor tab
//   4. builds the firmware and uploads it over WiFi (ArduinoOTA) to the lights it finds on the network
//
// Started by an AI assistant (MCP), it opens the editor in the browser unless ALITE2_UI_NO_BROWSER=1.
//
// The editor works on exactly one project: ui_studio/project/alite2_ui.json (+ assets/).
// "Export" writes the generated LVGL C files straight into the firmware sketch: src/Alite2/.
//
// If the port is already taken by another instance (e.g. run.sh or a second AI session),
// this process connects to it on /relay and forwards tool calls through it instead.
//
//   node mcp/server.js           MCP (stdio) + web server
//   node mcp/server.js --http    web server + bridge only (no MCP), same as `npm start`
