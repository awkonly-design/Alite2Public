import { firmwarePaths, otaConfig, compile, findDevices, findEspota, upload, factoryOta, normalizeOtaPassword, OTA_PASSWORD_HELP, OLD_FACTORY_MSG } from './firmware.js';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const PROJECT_DIR = path.join(ROOT, 'project');
const PROJECT_FILE = path.join(PROJECT_DIR, 'alite2_ui.json');
const ASSETS_DIR = path.join(PROJECT_DIR, 'assets');
const SKETCH_DIR = path.resolve(process.env.ALITE2_SKETCH_DIR || path.join(ROOT, '..', 'src', 'Alite2'));
const PORT = +(process.env.ALITE2_UI_PORT || 5190);
const HOST = '127.0.0.1';
const HTTP_ONLY = process.argv.includes('--http');
const log = (...a) => console.error('[alite2-ui]', ...a); // stdout is reserved for MCP
const TIMEOUT = 30000;
// relayed server calls that take longer than TIMEOUT
const LONG_TIMEOUTS = { build_run: 20 * 60e3, upload_run: 15 * 60e3, devices_scan: 60e3 };
const ALLOWED_ORIGINS = new Set([`http://127.0.0.1:${PORT}`, `http://localhost:${PORT}`]);
// Host header check blocks DNS-rebinding (a foreign domain resolving to 127.0.0.1)
const ALLOWED_HOSTS = new Set([`127.0.0.1:${PORT}`, `localhost:${PORT}`]);
// shared secret for relaying between local MCP processes; readable only by this user
const TOKEN_FILE = path.join(os.homedir(), '.alite2-ui-studio', `relay-${PORT}.token`);
const hmac = (key, msg) => crypto.createHmac('sha256', key).update(msg).digest('hex');
const safeEq = (a, b) => typeof a === 'string' && typeof b === 'string' && a.length === b.length && crypto.timingSafeEqual(Buffer.from(a), Buffer.from(b));
const rel = (f) => path.relative(path.join(ROOT, '..'), f) || f;

const MIME = { '.html': 'text/html; charset=utf-8', '.js': 'text/javascript; charset=utf-8', '.css': 'text/css; charset=utf-8', '.json': 'application/json', '.png': 'image/png' };
// generated files carry this marker in their first line; only such files are ever replaced or removed
// first-line markers of generated files (the old name is still recognised in files exported before the rename)
const GENERATED_MARKS = ['generated by Alite2 Studio', 'generated by Alite2 UI Studio'];
const hasMark = (l) => GENERATED_MARKS.some((m) => l.includes(m));

// ------------------------------------------------------------------ bridge (server role)
let editor = null;             // active editor tab socket
const editors = new Set();
const pending = new Map();     // id -> {resolve, reject, timer}
let seq = 1;
let backedUp = false;

function callEditor(method, params = {}) {
  if (!editor || editor.readyState !== WebSocket.OPEN) {
    return Promise.reject(new Error(`No Alite2 Studio editor tab is connected. Open http://${HOST}:${PORT} in a browser.`));
  }
  const id = seq++;
  return new Promise((resolve, reject) => {
    const timer = setTimeout(() => { pending.delete(id); reject(new Error(`Editor did not respond (${method})`)); }, TIMEOUT);
    pending.set(id, { resolve, reject, timer });
    editor.send(JSON.stringify({ type: 'req', id, method, params }));
  });
}


/** Trusted methods: called by this MCP process or an authenticated relay peer (i.e. on the AI assistant's behalf). */
const serverMethods = {
  read_project: () => readProject(),
  save_project: ({ text }) => writeProject(text),
  save_asset: ({ name, base64 }) => writeAsset(name, base64),
  import_asset: ({ source, name }) => importAsset(source, name),
  export_ui: ({ text }) => exportProject(text),
  widget_usage: ({ name }) => widgetUsage(name),
  build_run: ({ text }) => runExclusive(() => runBuild(text)),
  devices_scan: () => scanDevices(),
  upload_run: ({ targets }) => runExclusive(() => runUpload(targets)),
};
/** Methods the editor tab (browser) may call: saving the fixed project, adding PNG assets and a read-only reference check.
 *  Exporting is done through MCP (export_ui). */
const editorMethods = {
  save_project: ({ text }) => writeProject(text),
  save_asset: ({ name, base64 }) => writeAsset(name, base64), // PNG only, into project/assets/
  widget_usage: ({ name }) => widgetUsage(name),
  // firmware build & WiFi upload (progress is pushed to every editor tab as {type:'job'} messages)
  job_state: () => publicJob(),
  build_start: ({ text }) => { startJob(() => runBuild(text)); return { started: true }; },
  upload_prepare: () => prepareUpload(),
  devices_scan: () => scanDevices(),
  upload_start: ({ targets }) => { startJob(() => runUpload(targets)); return { started: true }; },
  upload_cancel: () => { uploadAbort?.abort(); return { cancelled: !!uploadAbort }; },
};

// ------------------------------------------------------------------ project I/O
async function readProject() {
  const text = await fs.readFile(PROJECT_FILE, 'utf8');
  const assets = [];
  let ents = [];
  try { ents = await fs.readdir(ASSETS_DIR); } catch { /* no assets */ }
  for (const name of ents.sort()) {
    if (!/\.png$/i.test(name)) continue;
    const buf = await fs.readFile(path.join(ASSETS_DIR, name));
    assets.push({ path: 'assets/' + name, mime: 'image/png', base64: buf.toString('base64') });
  }
  return { path: rel(PROJECT_FILE), fileName: path.basename(PROJECT_FILE), text, assets };
}

async function writeProject(text) {
  if (typeof text !== 'string') throw new Error('text is required');
  JSON.parse(text); // refuse to write broken JSON
  let backup = null;
  if (!backedUp) {
    try {
      const orig = await fs.readFile(PROJECT_FILE);
      const dir = path.join(PROJECT_DIR, 'backup');
      await fs.mkdir(dir, { recursive: true });
      const ts = new Date().toISOString().replace(/[-:]/g, '').replace('T', '_').slice(0, 15);
      backup = path.join(dir, `alite2_ui_${ts}.json`);
      await fs.writeFile(backup, orig);
      backup = rel(backup);
    } catch (e) { if (e.code !== 'ENOENT') throw e; }
    backedUp = true;
  }
  await fs.writeFile(PROJECT_FILE, text, 'utf8');
  return { path: rel(PROJECT_FILE), bytes: Buffer.byteLength(text), backup };
}

async function writeAsset(name, base64) {
  const n = String(name || '');
  if (!/^[\w.-]+\.png$/i.test(n)) throw new Error('Asset names must be .png files made of letters, digits, _ - . : ' + n);
  const buf = Buffer.from(String(base64 || ''), 'base64');
  if (buf.length < 8 || buf.readUInt32BE(0) !== 0x89504e47) throw new Error('Not a PNG file: ' + n);
  await fs.mkdir(ASSETS_DIR, { recursive: true });
  await fs.writeFile(path.join(ASSETS_DIR, n), buf);
  return { path: 'assets/' + n, bytes: buf.length };
}

/** Copy a local PNG file into project/assets/. */
async function importAsset(source, name) {
  const src = path.resolve(String(source || ''));
  if (!/\.png$/i.test(src)) throw new Error('Only PNG files can be added: ' + src);
  const buf = await fs.readFile(src);
  const n = String(name || path.basename(src)).replace(/[^\w.-]/g, '_');
  const r = await writeAsset(n, buf.toString('base64'));
  return { ...r, base64: buf.toString('base64') };
}

/** Generate the LVGL C sources of the project and write them next to the firmware .ino files. */
async function exportProject(text) {
  const data = JSON.parse(text ?? (await fs.readFile(PROJECT_FILE, 'utf8')));
  await checkProtected(data, PROJECT_DIR);   // QrScreen (regulatory information) must stay unchanged
  const readFile = async (r) => {
    const f = path.resolve(PROJECT_DIR, r);
    if (!f.startsWith(PROJECT_DIR + path.sep)) return null;
    try { return new Uint8Array(await fs.readFile(f)); } catch { return null; }
  };
  const listFiles = async () => { try { return (await fs.readdir(ASSETS_DIR)).filter((f) => !f.startsWith('.')).map((f) => 'assets/' + f); } catch { return []; } };
  const { files, warnings } = await exportUI(data, { readFile, listFiles, projectName: 'Alite2', allAssetImages: true });
  const flat = toSketchLayout(files);
  try { await fs.access(path.join(SKETCH_DIR, 'Alite2.ino')); }
  catch { throw new Error(`Firmware sketch folder not found: ${SKETCH_DIR} (set ALITE2_SKETCH_DIR)`); }
  const written = [];
  for (const [name, content] of Object.entries(flat)) {
    if (!isSketchUiFile(name)) continue;
    const target = path.join(SKETCH_DIR, name);
    if (await isHandWritten(target)) { warnings.push(`Not overwritten (hand-written file): ${name}`); continue; }
    await fs.writeFile(target, content);
    written.push(name);
  }
  // remove generated files that are no longer produced (deleted screens / images), so the sketch keeps compiling
  const removed = [];
  for (const name of await fs.readdir(SKETCH_DIR)) {
    if (!isSketchUiFile(name) || Object.hasOwn(flat, name)) continue;
    const f = path.join(SKETCH_DIR, name);
    if (await isGenerated(f)) { await fs.unlink(f); removed.push(name); }
  }
  log(`exported ${written.length} UI files to ${SKETCH_DIR}`);
  return { dir: rel(SKETCH_DIR), files: written, removed, warnings };
}
async function firstLine(f) { try { return (await fs.readFile(f, 'utf8')).split('\n', 1)[0]; } catch { return null; } }
async function isGenerated(f) { const l = await firstLine(f); return l != null && hasMark(l); }
async function isHandWritten(f) { const l = await firstLine(f); return l != null && !hasMark(l); }

/** Where the firmware code (not the generated UI files) uses ui_<name>. */
async function widgetUsage(name) {
  const id = 'ui_' + String(name || '').replace(/[^\w]/g, '_');
  const re = new RegExp(`\\b${id}\\b`);
  const hits = [];
  for (const f of (await fs.readdir(SKETCH_DIR)).sort()) {
    if (!/\.(ino|c|h|cpp)$/.test(f)) continue;
    const full = path.join(SKETCH_DIR, f);
    if (await isGenerated(full)) continue;
    const lines = (await fs.readFile(full, 'utf8')).split('\n');
    lines.forEach((l, i) => { if (re.test(l)) hits.push(`${f}:${i + 1}: ${l.trim()}`); });
  }
  return { variable: id, used_in_firmware: hits.length > 0, references: hits.slice(0, 200) };
}

// ------------------------------------------------------------------ firmware build / WiFi upload job
const FW = firmwarePaths(path.resolve(ROOT, '..'));
let job = null;
job = newJob('idle');
let pubTimer = null;

function newJob(phase) {
  return { id: Date.now(), running: false, phase, steps: [], log: [], devices: job?.devices || [], scanning: false, uploads: {}, error: null, summary: '' };
}
function publicJob() { return { ...job, log: job.log.slice(-200) }; }
function publish(now = false) {
  const send = () => { pubTimer = null; const msg = JSON.stringify({ type: 'job', state: publicJob() }); for (const e of editors) if (e.readyState === WebSocket.OPEN) e.send(msg); };
  if (now) { clearTimeout(pubTimer); send(); } else if (!pubTimer) pubTimer = setTimeout(send, 120);
}
const jobLog = (line) => { job.log.push(line); if (job.log.length > 400) job.log.splice(0, job.log.length - 400); };
const step = (key) => job.steps.find((s) => s.key === key);
function setStep(key, patch) { Object.assign(step(key), patch); publish(); }

/** Run a job unless one is running; the editor gets the result through job messages. */
function startJob(fn) {
  if (job.running) throw new Error('A build or upload is already running');
  fn().catch((e) => { job.running = false; job.phase = 'error'; job.error = e.message; publish(true); });
}
/** Run a job and wait for it (MCP). */
async function runExclusive(fn) {
  if (job.running) throw new Error('A build or upload is already running');
  return fn();
}

async function scanDevices() {
  job.scanning = true; publish(true);
  const fac = await factoryOta(ROOT);
  const r = await findDevices(3500, fac.hostname);
  job.devices = r.devices; job.scanning = false;
  if (r.error) jobLog(r.error);
  publish(true);
  return { devices: r.devices, error: r.error || null };
}

/** Export the UI from `text`, compile; scan for lights in parallel. */
async function runBuild(text) {
  job = newJob('build');
  job.running = true;
  // one gauge: exporting the UI code is the first 4 %, compiling the rest
  job.steps = [{ key: 'prepare', label: 'Prepare firmware', status: 'running', progress: 0, detail: 'Exporting UI code…' }];
  publish(true);
  const scan = scanDevices().catch(() => null);
  try {
    let ex;
    try { ex = await exportProject(text); }
    catch (e) { setStep('prepare', { status: 'error', detail: 'Export UI code: ' + e.message }); throw e; }
    for (const w of ex.warnings) jobLog('export: ' + w);
    jobLog(`export: ${ex.files.length} files → ${ex.dir}`);
    setStep('prepare', { progress: 0.04, detail: 'Compiling firmware…' });
    const r = await compile(FW, ({ progress, line }) => { step('prepare').progress = 0.04 + 0.96 * progress; if (line) jobLog(line); publish(); });
    if (!r.ok) {
      for (const l of r.tail || []) jobLog(l);
      setStep('prepare', { status: 'error', detail: (r.errors && r.errors[0]) || r.error });
      job.phase = 'error'; job.error = r.error; job.errors = r.errors;
      return { ok: false, error: r.error, errors: r.errors, tail: r.tail };
    }
    setStep('prepare', { status: 'done', progress: 1, detail: r.summary });
    job.summary = r.summary;
    job.phase = 'built';
    await scan;
    return { ok: true, bin: path.relative(FW.repoRoot, r.bin), summary: r.summary, devices: job.devices };
  } finally {
    job.running = false; publish(true);
  }
}

/** Toolbar "Upload": use the last build (build/Alite2.ino.bin) without compiling again; scan for lights. */
async function prepareUpload() {
  if (job.running) throw new Error('A build or upload is already running');
  let st;
  try { st = await fs.stat(FW.bin); } catch { throw new Error('No firmware binary yet — press Build first'); }
  const when = new Date(st.mtimeMs).toLocaleString();
  job = newJob('built');
  job.summary = `Last build: ${when} (${st.size.toLocaleString()} bytes)`;
  job.steps = [{ key: 'prepare', label: 'Firmware (last build)', status: 'done', progress: 1, detail: job.summary }];
  publish(true);
  scanDevices().catch(() => null);
  return { ready: true, summary: job.summary };
}

/**
 * Upload build/Alite2.ino.bin to the given lights ({ip, port, name, factory?, password?}) in parallel.
 * Every light needs the 8-character password shown on its LCD (Setup > Radio, bottom, under the IP address), given
 * per target. Old factory firmware lights (HDS-15W, below 1.2.6) are refused: they must be updated to 1.2.6+ first. Passwords are never logged or kept in the job state.
 */
let uploadAbort = null;   // AbortController of the running upload (Cancel in the editor)
async function runUpload(targets) {
  if (!Array.isArray(targets) || !targets.length) throw new Error('No devices selected');
  try { await fs.access(FW.bin); } catch { throw new Error('No firmware binary yet — build first'); }
  const espota = await findEspota();
  if (!espota) throw new Error('espota.py not found — run ./scripts/setup.sh (esp32 core 3.0.2)');
  const cfg = await otaConfig(FW);
  const known = new Map((job.devices || []).map((d) => [`${d.ip}:${d.port}`, d]));
  const prev = job;
  job = newJob('upload');
  job.steps = prev.steps; job.summary = prev.summary; job.devices = prev.devices;
  job.running = true;
  uploadAbort = new AbortController();
  const { signal } = uploadAbort;
  const key = (t) => `${t.ip}:${t.port || cfg.port}`;
  for (const t of targets) job.uploads[key(t)] = { name: t.name || t.ip, progress: 0, status: 'pending' };
  publish(true);
  const results = [];
  let next = 0;
  const worker = async () => {
    while (next < targets.length) {
      const t = targets[next++];
      const u = job.uploads[key(t)];
      if (signal.aborted) { Object.assign(u, { status: 'error', error: 'Cancelled' }); results.push({ device: u.name, ip: t.ip, ok: false, error: 'Cancelled' }); publish(); continue; }
      u.status = 'running'; publish();
      const fail = (error) => { Object.assign(u, { status: 'error', error }); jobLog(`${u.name} (${t.ip}): failed — ${error}`); results.push({ device: u.name, ip: t.ip, ok: false, error }); publish(); };
      // old factory firmware lights (HDS-15W, below 1.2.6) cannot use Alite2Public; all other lights need the
      // password shown on their LCD, given per target
      const dev = known.get(key(t));
      if (t.factory ?? dev?.factory) { fail(OLD_FACTORY_MSG); continue; }
      const given = normalizeOtaPassword(t.password);
      if (!given) { fail(t.password ? `Invalid OTA password. ${OTA_PASSWORD_HELP}` : OTA_PASSWORD_HELP); continue; }
      const onPr = (pr, stage) => { u.progress = pr; if (stage) u.stage = stage; publish(); };
      const r = await upload({ espota, bin: FW.bin, ip: t.ip, port: t.port || cfg.port, password: given, signal }, onPr);
      if (!r.ok && /auth/i.test(r.error || '')) r.error = `Wrong OTA password (${r.error}). ${OTA_PASSWORD_HELP}; it changes when the light's IP address changes.`;
      Object.assign(u, r.ok ? { status: 'done', progress: 1 } : { status: 'error', error: r.error });
      jobLog(`${u.name} (${t.ip}): ${r.ok ? 'uploaded' : 'failed — ' + r.error}`);
      results.push({ device: u.name, ip: t.ip, ok: r.ok, error: r.error || null });
      publish();
    }
  };
  try {
    await Promise.all(Array.from({ length: Math.min(4, targets.length) }, worker));
    job.phase = 'done';
    if (signal.aborted) job.cancelled = true;
    return { results };
  } finally {
    uploadAbort = null;
    job.running = false; publish(true);
  }
}

function startServer() {
  return new Promise((resolve, reject) => {
    const server = http.createServer(async (req, res) => {
      if (!ALLOWED_HOSTS.has(req.headers.host)) { res.writeHead(421); res.end('misdirected request'); return; }
      try {
        const url = new URL(req.url, `http://${HOST}`);
        if (url.pathname === '/api/project') {
          const proj = await readProject();
          res.writeHead(200, { 'content-type': 'application/json', 'cache-control': 'no-store' });
          res.end(JSON.stringify(proj));
          return;
        }
        if (url.pathname === '/bridge/status') {
          res.writeHead(200, { 'content-type': 'application/json' });
          res.end(JSON.stringify({ editors: editors.size, active: !!editor }));
          return;
        }
        let rel = decodeURIComponent(url.pathname);
        if (rel.endsWith('/')) rel += 'index.html';
        const file = path.join(ROOT, path.normalize(rel));
        if (!file.startsWith(ROOT + path.sep) || /[\\/](node_modules|\.git|mcp|project)[\\/]/.test(file.slice(ROOT.length))) { res.writeHead(403); res.end(); return; }
        const data = await fs.readFile(file);
        res.writeHead(200, { 'content-type': MIME[path.extname(file).toLowerCase()] || 'application/octet-stream', 'cache-control': 'no-cache' });
        res.end(data);
      } catch {
        res.writeHead(404); res.end('not found');
      }
    });
    const wss = new WebSocketServer({ noServer: true });
    server.on('upgrade', (req, socket, head) => {
      if (!ALLOWED_HOSTS.has(req.headers.host)) { socket.destroy(); return; }
      const { pathname } = new URL(req.url, `http://${HOST}`);
      // only accept browser connections from our own origin (blocks other web pages from driving the bridge)
      const origin = req.headers.origin;
      if (pathname === '/bridge' && !ALLOWED_ORIGINS.has(origin)) { socket.destroy(); return; }
      // the relay is for other local MCP processes only; browsers always send Origin, Node clients don't
      if (pathname === '/relay' && origin) { socket.destroy(); return; }
      if (pathname !== '/bridge' && pathname !== '/relay') { socket.destroy(); return; }
      wss.handleUpgrade(req, socket, head, (ws) => (pathname === '/bridge' ? onEditor(ws) : onRelay(ws)));
    });
    server.once('error', reject);
    server.listen(PORT, HOST, () => { writeToken(); log(`web app: http://${HOST}:${PORT}`); resolve(server); });
  });
}

let relayToken = null;
function writeToken() {
  relayToken = crypto.randomBytes(32).toString('hex');
  fsSync.mkdirSync(path.dirname(TOKEN_FILE), { recursive: true, mode: 0o700 });
  fsSync.writeFileSync(TOKEN_FILE, relayToken, { mode: 0o600 });
  fsSync.chmodSync(TOKEN_FILE, 0o600);
  process.on('exit', () => { try { if (fsSync.readFileSync(TOKEN_FILE, 'utf8') === relayToken) fsSync.unlinkSync(TOKEN_FILE); } catch { /* ignore */ } });
  for (const sig of ['SIGINT', 'SIGTERM']) process.on(sig, () => process.exit(0));
}

function onEditor(ws) {
  editors.add(ws);
  editor = ws;
  log(`editor tab connected (${editors.size})`);
  ws.send(JSON.stringify({ type: 'hello', role: 'active' }));
  ws.on('message', async (raw) => {
    let msg; try { msg = JSON.parse(raw); } catch { return; }
    if (msg.type === 'res') {
      const p = pending.get(msg.id); if (!p) return;
      pending.delete(msg.id); clearTimeout(p.timer);
      msg.error ? p.reject(new Error(msg.error)) : p.resolve(msg.result);
    } else if (msg.type === 'focus') {
      editor = ws;
      for (const e of editors) e.send(JSON.stringify({ type: 'role', role: e === ws ? 'active' : 'standby' }));
    } else if (msg.type === 'req') {
      try {
        const fn = Object.hasOwn(editorMethods, msg.method) ? editorMethods[msg.method] : null;
        if (!fn) throw new Error('Request not allowed: ' + msg.method);
        ws.send(JSON.stringify({ type: 'res', id: msg.id, result: await fn(msg.params || {}) }));
      }
      catch (e) { ws.send(JSON.stringify({ type: 'res', id: msg.id, error: e.message })); }
    }
  });
  ws.on('close', () => {
    editors.delete(ws);
    if (editor === ws) { editor = [...editors].pop() || null; editor?.send(JSON.stringify({ type: 'role', role: 'active' })); }
    log(`editor tab disconnected (${editors.size})`);
  });
}

// another MCP process forwarding its tool calls through us
function onRelay(ws) {
  // mutual challenge/response with the token file so only same-user MCP processes can relay
  const nonce = crypto.randomBytes(16).toString('hex');
  let authed = false;
  ws.send(JSON.stringify({ type: 'challenge', nonce }));
  const kill = setTimeout(() => { if (!authed) ws.terminate(); }, 5000);
  ws.on('message', async (raw) => {
    let msg; try { msg = JSON.parse(raw); } catch { return; }
    if (!authed) {
      if (msg.type === 'auth' && relayToken && safeEq(msg.mac, hmac(relayToken, 'client:' + nonce)) && typeof msg.nonce === 'string') {
        authed = true; clearTimeout(kill);
        ws.send(JSON.stringify({ type: 'auth_ok', mac: hmac(relayToken, 'server:' + msg.nonce) }));
      } else { log('relay authentication failed'); ws.terminate(); }
      return;
    }
    if (msg.type !== 'req') return;
    if (msg.server && !Object.hasOwn(serverMethods, msg.method)) { ws.send(JSON.stringify({ type: 'res', id: msg.id, error: 'unknown method' })); return; }
    try {
      const result = msg.server ? await serverMethods[msg.method](msg.params || {}) : await callEditor(msg.method, msg.params);
      ws.send(JSON.stringify({ type: 'res', id: msg.id, result }));
    } catch (e) { ws.send(JSON.stringify({ type: 'res', id: msg.id, error: e.message })); }
  });
}

// ------------------------------------------------------------------ relay (client role)
let relay = null;
function connectRelay() {
  return new Promise((resolve, reject) => {
    let token;
    try { token = fsSync.readFileSync(TOKEN_FILE, 'utf8').trim(); }
    catch { reject(new Error(`Port ${PORT} is used by another program and there is no Alite2 Studio token file (set ALITE2_UI_PORT to use another port)`)); return; }
    const ws = new WebSocket(`ws://${HOST}:${PORT}/relay`);
    const rp = new Map();
    let rid = 1;
    const myNonce = crypto.randomBytes(16).toString('hex');
    let ready = false;
    const fail = (why) => { log('relay:', why); ws.terminate(); reject(new Error(`The server on port ${PORT} is not trusted: ${why}`)); };
    const authTimer = setTimeout(() => { if (!ready) fail('authentication timed out'); }, 5000);
    const onReady = () => {
      ready = true; clearTimeout(authTimer);
      log(`port ${PORT} is in use — relaying through the running instance`);
      relay = {
        call: (method, params, server = false) => new Promise((res, rej) => {
          if (ws.readyState !== WebSocket.OPEN) { rej(new Error('Lost the connection to the Alite2 Studio server')); return; }
          const id = rid++;
          const timer = setTimeout(() => { rp.delete(id); rej(new Error(`Timed out (${method})`)); }, (LONG_TIMEOUTS[method] || TIMEOUT) + 2000);
          rp.set(id, { res, rej, timer });
          ws.send(JSON.stringify({ type: 'req', id, method, params, server }));
        }),
      };
      resolve();
    };
    ws.on('message', (raw) => {
      let msg; try { msg = JSON.parse(raw); } catch { return; }
      if (!ready) {
        if (msg.type === 'challenge' && typeof msg.nonce === 'string') ws.send(JSON.stringify({ type: 'auth', mac: hmac(token, 'client:' + msg.nonce), nonce: myNonce }));
        else if (msg.type === 'auth_ok' && safeEq(msg.mac, hmac(token, 'server:' + myNonce))) onReady();
        else fail('invalid authentication response');
        return;
      }
      const p = rp.get(msg.id); if (!p) return;
      rp.delete(msg.id); clearTimeout(p.timer);
      msg.error ? p.rej(new Error(msg.error)) : p.res(msg.result);
    });
    ws.on('error', reject);
    ws.on('close', () => { relay = null; log('relay connection closed'); });
  });
}

let serverUp = false;
/** Make sure we either own the port or relay through whoever does (the owner may have exited). */
async function ensureBridge() {
  if (serverUp || relay) return;
  try { await startServer(); serverUp = true; }
  catch (e) { if (e.code !== 'EADDRINUSE') throw e; await connectRelay(); }
}
const call = async (method, params) => { await ensureBridge(); return relay ? relay.call(method, params) : callEditor(method, params); };
const callServer = async (method, params) => { await ensureBridge(); return relay ? relay.call(method, params, true) : serverMethods[method](params); };

